// Bundle the live-character function into one self-contained file, so Vercel
// runs it without resolving TypeScript imports from src/ at runtime.
import { build } from 'esbuild';

await build({
  entryPoints: ['server/encounter.ts'],
  outfile: 'api/encounter.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  banner: { js: '// Generated by scripts/build-api.mjs from server/encounter.ts. Do not edit.' },
  logLevel: 'warning',
});
console.log('api/encounter.js built');
